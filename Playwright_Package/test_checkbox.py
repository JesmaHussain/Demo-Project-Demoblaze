from playwright.sync_api import Page
import time
class TestCheckbox:
    def test_checkbox(self,page: Page):
        page.goto("https://selenium.qabible.in/check-box-demo.php")
        time.sleep(3)
        single_checkbox=page.locator("//input[@id='gridCheck']")
        time.sleep(3)
        print(single_checkbox.is_checked())
        time.sleep(3)
        single_checkbox.check()
        print(single_checkbox.is_checked())
        time.sleep(3)
        result=page.locator("//div[@id='message-one']")
        print(result.text_content())
        page.get_by_role("button",name="Select All").click()
        time.sleep(3)
        check1=page.get_by_label("Check box One")
        check2=page.get_by_label("Check box Two")
        check3=page.get_by_label("Check box Three")
        check4=page.get_by_label("Check box Four")
        print(check1.is_checked())
        print(check2.is_checked())
        print(check3.is_checked())
        print(check4.is_checked())
        time.sleep(3)
        page.get_by_role("button", name="UnSelect All").click()
        time.sleep(3)
        check1.check()
        check4.check()
        time.sleep(3)
        print(check1.is_checked())
        print(check2.is_checked())
        print(check3.is_checked())
        print(check4.is_checked())